/* 作品集图片路径：按「未标题-1-XX.png」顺序生成 */
function seq(dir, from, to) {
  const a = [];
  for (let i = from; i <= to; i++) a.push(dir + '未标题-1-' + String(i).padStart(2, '0') + '.jpg');
  return a;
}

